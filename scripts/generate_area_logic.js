import fs from 'fs';
import path from 'path';

const csvPath = path.join(process.cwd(), 'public/assets/aistudio/agency_master__bally__404758a5.csv');
const raw = fs.readFileSync(csvPath, 'utf8');
const lines = raw.split(/\r?\n/).map(l => l.trim()).filter(Boolean);

const rows = [];

for (let i = 1; i < lines.length; i++) {
  const line = lines[i];
  const parts = line.split(',');
  if (parts.length >= 4) {
    const areaCode = parts[0].trim();
    const areaName = parts[1].trim();
    const agencyCode = parts[2].trim();
    const agencyName = parts.slice(3).join(',').trim();
    rows.push({
      AREA_CODE: areaCode,
      AREA_NAME: areaName,
      AGENCY_CODE: agencyCode,
      AGENCY_NAME: agencyName
    });
  }
}

console.log(`Parsed ${rows.length} Area-Agency mappings from CSV.`);

// Generate SQL migration file
let sql = `-- Migration: Create area_logic table and populate Area-Agency mappings\n`;
sql += `BEGIN;\n\n`;
sql += `CREATE TABLE IF NOT EXISTS area_logic (\n`;
sql += `    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\n`;
sql += `    "AREA_CODE" TEXT NOT NULL,\n`;
sql += `    "AREA_NAME" TEXT NOT NULL,\n`;
sql += `    "AGENCY_CODE" TEXT NOT NULL,\n`;
sql += `    "AGENCY_NAME" TEXT NOT NULL,\n`;
sql += `    CONSTRAINT area_logic_code_unique UNIQUE ("AREA_CODE", "AGENCY_CODE")\n`;
sql += `);\n\n`;
sql += `CREATE INDEX IF NOT EXISTS idx_area_logic_area_code ON area_logic ("AREA_CODE");\n`;
sql += `CREATE INDEX IF NOT EXISTS idx_area_logic_area_name ON area_logic ("AREA_NAME");\n\n`;
sql += `ALTER TABLE area_logic ENABLE ROW LEVEL SECURITY;\n`;
sql += `DROP POLICY IF EXISTS "Allow public read and write on area_logic" ON area_logic;\n`;
sql += `CREATE POLICY "Allow public read and write on area_logic" ON area_logic FOR ALL USING (true) WITH CHECK (true);\n\n`;

sql += `INSERT INTO area_logic ("AREA_CODE", "AREA_NAME", "AGENCY_CODE", "AGENCY_NAME") VALUES\n`;
const valStrings = rows.map(r => `('${r.AREA_CODE.replace(/'/g, "''")}', '${r.AREA_NAME.replace(/'/g, "''")}', '${r.AGENCY_CODE.replace(/'/g, "''")}', '${r.AGENCY_NAME.replace(/'/g, "''")}')`);
sql += valStrings.join(',\n');
sql += `\nON CONFLICT ("AREA_CODE", "AGENCY_CODE") DO UPDATE SET "AREA_NAME" = EXCLUDED."AREA_NAME", "AGENCY_NAME" = EXCLUDED."AGENCY_NAME";\n\n`;
sql += `COMMIT;\n`;

fs.writeFileSync(path.join(process.cwd(), 'migrations/20261023_create_area_logic.sql'), sql);
console.log('Wrote migrations/20261023_create_area_logic.sql');

// Generate TypeScript AreaLogic master data file
let tsContent = `// Auto-generated master dataset for Area-Agency mappings (area_logic)
export interface AreaLogicRecord {
  AREA_CODE: string;
  AREA_NAME: string;
  AGENCY_CODE: string;
  AGENCY_NAME: string;
}

export const AREA_LOGIC_MASTER_DATA: AreaLogicRecord[] = ${JSON.stringify(rows, null, 2)};
`;

fs.writeFileSync(path.join(process.cwd(), 'src/data/areaLogicMasterData.ts'), tsContent);
console.log('Wrote src/data/areaLogicMasterData.ts');
